_COMPILED = [(t, name, d, re.compile(p)) for t, name, d, p in RULES]
TYPE_NAMES = {t: name for t, name, _, _ in RULES} | {"other": "其他公告", "market": "市場事件", "news": "新聞"}


def classify(title: str) -> tuple[str, int]:
    """主旨 → (類型, 方向)。"""
    t = re.sub(r"\s+", "", title or "")
    for type_, _, direction, rx in _COMPILED:
        if rx.search(t):
            # 少數可從主旨判斷方向的情況
            if type_ in ("earnings", "revenue"):
                if re.search(r"虧損|減少|衰退|下滑|減損", t):
                    return type_, -1
                if re.search(r"創.*新高|成長|增加", t):
                    return type_, 1
            return type_, direction
    return "other", 0
